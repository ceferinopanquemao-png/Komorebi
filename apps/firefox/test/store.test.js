import {test} from 'node:test';
import assert from 'node:assert/strict';
import 'fake-indexeddb/auto';
import {store} from '../src/store.js';
import {getDocument} from '../src/db.js';
import {unlockVault,readRecords,pack,recordId} from '../src/crypto.js';
import {ConflictError} from '../src/merge.js';
const password='a long integration password',date='2026-11-15';
const entry=title=>({title,body:'Confidential integration text',mood:'happy',starred:true});
test('encrypted persistence, offline merge, conflict resolution, tombstones and remote races',async()=>{
 let remote=null,version=0,race=false;
 globalThis.fetch=async(url,args)=>{
  if(args.method==='GET')return remote?new Response(JSON.stringify(remote),{headers:{ETag:`"${version}"`}}):new Response(null,{status:404});
  if(race)return new Response(null,{status:412});
  assert.equal(args.headers[remote?'If-Match':'If-None-Match'],remote?`"${version}"`:'*');
  remote=JSON.parse(args.body);version++;return new Response(null,{status:201,headers:{ETag:`"${version}"`}});
 };
 assert.equal(await store.exists(),false);await store.create(password);
 await store.save({entries:{[date]:entry('Local secret title')}});
 const doc=await getDocument(),raw=JSON.stringify(doc);assert.ok(!raw.includes('Confidential'));assert.ok(!raw.includes(date));
 await store.configure({url:'https://dav.example/test.vault',user:'private-user',password:'private-webdav-password'});
 assert.ok(!JSON.stringify(await getDocument()).includes('private-webdav-password'));
 await store.sync();assert.ok(remote);
 const beforeEdit=await readRecords(remote,await unlockVault(remote,password));
 await store.lock();const uiData=await store.unlock(password);uiData.entries[date].title='Edited through UI reference';await store.save(uiData);await store.sync();
 const afterEdit=await readRecords(remote,await unlockVault(remote,password));
 assert.notEqual(Object.values(beforeEdit)[0].rev,Object.values(afterEdit)[0].rev);
 await store.save({entries:{[date]:entry('Local secret title')}});await store.sync();
 const keys=await unlockVault(remote,password),id=await recordId(date,keys),records=await readRecords(remote,keys);
 records[id]={...records[id],entry:entry('Remote edit'),rev:'remote-1'};remote=await pack(remote,records,keys);version++;
 await store.save({entries:{[date]:entry('Local secret title'),'2026-11-16':entry('Independent day')}});
 let result=await store.sync();assert.equal(result.entries[date].title,'Remote edit');assert.ok(result.entries['2026-11-16']);
 const changed=await readRecords(remote,keys);changed[id]={...changed[id],entry:entry('Other device'),rev:'remote-2'};remote=await pack(remote,changed,keys);version++;
 await store.save({entries:{...result.entries,[date]:entry('Offline same day')}});
 await assert.rejects(store.sync(),ConflictError);
 result=await store.sync({[id]:'remote'});assert.equal(result.entries[date].title,'Other device');
 await store.save({entries:{}});await store.sync();const deleted=await readRecords(remote,keys);assert.ok(Object.values(deleted).every(r=>r.deleted));
 await store.save({entries:{[date]:entry('Kept locally after a race')}});
 const before=await getDocument();race=true;await assert.rejects(store.sync(),/Nothing was overwritten/);assert.deepEqual(await getDocument(),before);
 await store.lock();await assert.rejects(store.unlock('incorrect password long'),/Incorrect password/);
 result=await store.unlock(password);assert.equal(result.entries[date].title,'Kept locally after a race');
 await store.lock();await assert.rejects(store.restore('{"broken":true}',password));assert.deepEqual(await getDocument(),before);
 const backup=JSON.stringify(before.vault);await store.restore(backup,password);assert.equal((await store.unlock(password)).entries[date].title,'Kept locally after a race');
});
